-- 1. Jadvallarni qayta yaratish (agar mavjud bo'lsa o'chirish)
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;

-- Mijozlar jadvali
CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    gender VARCHAR(10) NOT NULL,
    registration_date DATE NOT NULL,
    acquisition_channel VARCHAR(50) NOT NULL
);

-- Mahsulotlar jadvali
CREATE TABLE products (
    product_id INT PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL,
    cost_price NUMERIC(12, 2) NOT NULL,    -- Mahsulotning Korzinkaga kelish tannarxi (so'mda)
    selling_price NUMERIC(12, 2) NOT NULL -- Mahsulotning rastadagi sotilish narxi (so'mda)
);

-- Buyurtmalar / Cheklar jadvali
CREATE TABLE orders (
    order_id INT PRIMARY KEY,
    customer_id INT NOT NULL REFERENCES customers(customer_id),
    order_date DATE NOT NULL,
    order_status VARCHAR(20) NOT NULL,    -- 'Yetkazildi', 'Bekor qilindi'
    payment_method VARCHAR(30) NOT NULL   -- 'UzumPay', 'Click', 'Payme', 'Plastik karta', 'Naqd pul'
);

-- Savat tarkibi (chek detallari)
CREATE TABLE order_items (
    order_item_id INT PRIMARY KEY,
    order_id INT NOT NULL REFERENCES orders(order_id),
    product_id INT NOT NULL REFERENCES products(product_id),
    quantity INT NOT NULL,                -- Xarid qilingan mahsulot soni yoki og'irligi
    discount_percent INT DEFAULT 0        -- Chegirma foizi (0, 5, 10, 15, 20)
);

